create or replace function private.validate_fine_links()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.driver_id is not null and not exists (
    select 1 from public.drivers d where d.id = new.driver_id and d.user_id = new.user_id
  ) then
    raise exception 'Driver not found';
  end if;
  if new.settlement_id is not null and not exists (
    select 1 from public.weekly_settlements s where s.id = new.settlement_id and s.user_id = new.user_id and s.driver_id = new.driver_id
  ) then
    raise exception 'Settlement not found';
  end if;
  return new;
end;
$$;
create trigger fines_validate_links
  before insert or update of driver_id, settlement_id, user_id on public.fines
  for each row execute function private.validate_fine_links();
revoke all on all functions in schema private from public, anon, authenticated;

-- Fuel use per vehicle and driver in a period, next to the vehicle's own baseline
-- (the 12 weeks before the period, or all other weeks when that is too little data).
create or replace function public.fuel_consumption_by_driver(p_from date, p_to date)
returns table (car_id bigint, driver_id bigint, distance double precision, fuel_used double precision, consumption double precision, baseline double precision)
language sql
stable
set search_path = ''
as $$
  with period as (
    select t.car_id, coalesce(t.driver_id, public.driver_for_car_on(t.car_id, t.date)) as driver_id, t.distance, t.fuel_used
    from public.trips t
    where t.status = 'done' and t.date between p_from and p_to
  ),
  grouped as (
    select p.car_id, p.driver_id, sum(p.distance) as distance, sum(p.fuel_used) as fuel_used
    from period p group by p.car_id, p.driver_id
  ),
  history as (
    select t.car_id,
      sum(t.fuel_used) filter (where t.date >= p_from - 84 and t.date < p_from) as recent_fuel,
      sum(t.distance) filter (where t.date >= p_from - 84 and t.date < p_from) as recent_km,
      sum(t.fuel_used) filter (where t.date < p_from or t.date > p_to) as other_fuel,
      sum(t.distance) filter (where t.date < p_from or t.date > p_to) as other_km
    from public.trips t
    where t.status = 'done' and t.car_id in (select g.car_id from grouped g)
    group by t.car_id
  )
  select g.car_id, g.driver_id, g.distance, g.fuel_used,
    case when g.distance > 0 then g.fuel_used / g.distance * 100 end,
    case
      when h.recent_km >= 300 then h.recent_fuel / h.recent_km * 100
      when h.other_km >= 300 then h.other_fuel / h.other_km * 100
    end
  from grouped g
  left join history h on h.car_id = g.car_id
$$;
revoke all on function public.fuel_consumption_by_driver(date, date) from public, anon;
grant execute on function public.fuel_consumption_by_driver(date, date) to authenticated;

