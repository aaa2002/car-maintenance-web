-- Logs a plan as done: one transaction adds the repair, moves the plan forward and raises the odometer.
create or replace function public.complete_service(
  p_plan_id bigint, p_date date, p_mileage_km double precision, p_price double precision, p_currency text, p_notes text default null
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  v_plan public.service_plans;
  v_repair_id bigint;
begin
  select * into v_plan from public.service_plans where id = p_plan_id;
  if not found then raise exception 'Service plan not found'; end if;
  if p_date > current_date then raise exception 'Completed entries cannot be in the future.'; end if;

  insert into public.repairs (user_id, car_id, status, currency, notification_ids, mileage_km, title, date, price, notes)
  values (v_plan.user_id, v_plan.car_id, 'done', p_currency, '{}', p_mileage_km, v_plan.title, p_date, coalesce(p_price, 0), nullif(trim(p_notes), ''))
  returning id into v_repair_id;

  update public.service_plans
  set last_done_on = p_date, last_done_km = coalesce(p_mileage_km, last_done_km)
  where id = p_plan_id;

  if p_mileage_km is not null then
    update public.cars set mileage_km = p_mileage_km
    where id = v_plan.car_id and (mileage_km is null or mileage_km < p_mileage_km);
  end if;
  return v_repair_id;
end;
$$;
revoke all on function public.complete_service(bigint, date, double precision, double precision, text, text) from public, anon;
grant execute on function public.complete_service(bigint, date, double precision, double precision, text, text) to authenticated;

