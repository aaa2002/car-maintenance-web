-- When the odometer was last read, so service plans can project today's mileage from the driving rate.
create or replace function private.touch_mileage_updated_on()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.mileage_km is distinct from old.mileage_km then
    new.mileage_updated_on := current_date;
  end if;
  return new;
end;
$$;
create trigger cars_touch_mileage_updated_on
  before update of mileage_km on public.cars
  for each row execute function private.touch_mileage_updated_on();

