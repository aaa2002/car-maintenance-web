-- Settlements: cash the driver already holds is its own line, and payouts record when and how they were paid.
-- The derived columns are recreated so the net amount subtracts that cash.
drop index if exists public.weekly_settlements_user_status_idx;
alter table public.weekly_settlements
  drop column status,
  drop column outstanding_amount,
  drop column net_amount;
alter table public.weekly_settlements
  add column cash_collected double precision not null default 0 check (cash_collected >= 0),
  add column paid_on date,
  add column payment_method text check (payment_method in ('bank', 'cash', 'other')),
  add column net_amount double precision generated always as (
    bolt_earnings + uber_earnings + bonuses + manual_adjustment
    - fleet_commission - vehicle_rent - expenses - fines - cash_collected
  ) stored,
  add column outstanding_amount double precision generated always as (
    case
      when bolt_earnings + uber_earnings + bonuses + manual_adjustment
        - fleet_commission - vehicle_rent - expenses - fines - cash_collected >= 0
      then greatest(
        bolt_earnings + uber_earnings + bonuses + manual_adjustment
        - fleet_commission - vehicle_rent - expenses - fines - cash_collected - amount_settled,
        0
      )
      else least(
        bolt_earnings + uber_earnings + bonuses + manual_adjustment
        - fleet_commission - vehicle_rent - expenses - fines - cash_collected + amount_settled,
        0
      )
    end
  ) stored,
  add column status text generated always as (
    case
      when abs(
        bolt_earnings + uber_earnings + bonuses + manual_adjustment
        - fleet_commission - vehicle_rent - expenses - fines - cash_collected
      ) <= 0.005
        or amount_settled >= abs(
          bolt_earnings + uber_earnings + bonuses + manual_adjustment
          - fleet_commission - vehicle_rent - expenses - fines - cash_collected
        ) - 0.005
      then 'paid'
      when amount_settled > 0.005 then 'partial'
      else 'unpaid'
    end
  ) stored;
create index weekly_settlements_user_status_idx on public.weekly_settlements (user_id, status, due_date);

-- Shared check for tables that link a driver with a plain foreign key (so deleting the driver only clears the link).
create or replace function private.validate_driver_owner()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.driver_id is not null and not exists (
    select 1 from public.drivers d where d.id = new.driver_id and d.user_id = new.user_id
  ) then
    raise exception 'Driver not found';
  end if;
  return new;
end;
$$;
revoke all on function private.validate_driver_owner() from public, anon, authenticated;

