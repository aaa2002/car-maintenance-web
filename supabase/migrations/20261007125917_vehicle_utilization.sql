-- Vehicle utilization: each day a ride-sharing car is driving (assigned), off the road (downtime) or idle.
-- Idle and off-road days are rent the fleet does not collect.

create table public.vehicle_downtime (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  car_id bigint not null references public.cars (id) on delete cascade,
  starts_on date not null,
  ends_on date,
  reason text not null default 'repair' check (reason in ('repair', 'accident', 'inspection', 'other')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vehicle_downtime_dates_check check (ends_on is null or ends_on >= starts_on)
);
-- A car is either off the road or not: at most one open period.
create unique index vehicle_downtime_open_key on public.vehicle_downtime (car_id) where ends_on is null;
create index vehicle_downtime_user_idx on public.vehicle_downtime (user_id);
create index vehicle_downtime_car_idx on public.vehicle_downtime (car_id, starts_on desc);
create trigger vehicle_downtime_set_updated_at
  before update on public.vehicle_downtime
  for each row execute function public.set_vehix_updated_at();
create trigger vehicle_downtime_validate_car_owner
  before insert or update of car_id, user_id on public.vehicle_downtime
  for each row execute function public.validate_vehix_car_owner();

alter table public.vehicle_downtime enable row level security;
create policy vehicle_downtime_select_own on public.vehicle_downtime for select to authenticated using ((select auth.uid()) = user_id);
create policy vehicle_downtime_insert_own on public.vehicle_downtime for insert to authenticated with check ((select auth.uid()) = user_id);
create policy vehicle_downtime_update_own on public.vehicle_downtime for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy vehicle_downtime_delete_own on public.vehicle_downtime for delete to authenticated using ((select auth.uid()) = user_id);
revoke all on public.vehicle_downtime from anon;
grant select, insert, update, delete on public.vehicle_downtime to authenticated;
grant usage, select on sequence public.vehicle_downtime_id_seq to authenticated;

-- Per ride-sharing car for a period (days up to today): driven, off-road and idle days, the weekly rent
-- the car usually earns (average of its last 8 settlements, else the fleet average, in p_currency),
-- and today's state with the day it started.
create or replace function public.fleet_utilization(p_from date, p_to date, p_currency text)
returns table (
  car_id bigint, days integer, driven_days integer, downtime_days integer, idle_days integer,
  weekly_rent double precision, state text, state_since date
)
language sql
stable
set search_path = ''
as $$
  with cars as (
    -- A car counts from its first assignment or when it was added, whichever is earlier.
    select c.id, least(c.created_at::date, coalesce((select min(a.starts_on) from public.driver_assignments a where a.car_id = c.id), c.created_at::date)) as start_day
    from public.cars c
    where c.ridesharing
  ),
  days as (
    select c.id as car_id, d::date as day
    from cars c
    cross join lateral generate_series(greatest(p_from, c.start_day), least(p_to, current_date), interval '1 day') d
  ),
  classified as (
    select d.car_id, d.day,
      exists (select 1 from public.vehicle_downtime v where v.car_id = d.car_id and v.starts_on <= d.day and (v.ends_on is null or v.ends_on >= d.day)) as off_road,
      exists (select 1 from public.driver_assignments a where a.car_id = d.car_id and a.starts_on <= d.day and (a.ends_on is null or a.ends_on >= d.day)) as driven
    from days d
  ),
  totals as (
    select k.car_id, count(*)::integer as days,
      (count(*) filter (where k.driven and not k.off_road))::integer as driven_days,
      (count(*) filter (where k.off_road))::integer as downtime_days,
      (count(*) filter (where not k.driven and not k.off_road))::integer as idle_days
    from classified k
    group by k.car_id
  ),
  recent_rent as (
    select x.car_id, avg(x.rent) as rent
    from (
      select s.car_id, public.convert_currency(s.vehicle_rent, s.currency, p_currency, s.week_start) as rent,
        row_number() over (partition by s.car_id order by s.week_start desc) as rn
      from public.weekly_settlements s
      where s.vehicle_rent > 0 and s.car_id is not null
    ) x
    where x.rn <= 8
    group by x.car_id
  ),
  fleet_rent as (select avg(r.rent) as rent from recent_rent r)
  select c.id, coalesce(t.days, 0), coalesce(t.driven_days, 0), coalesce(t.downtime_days, 0), coalesce(t.idle_days, 0),
    coalesce(r.rent, (select f.rent from fleet_rent f)),
    case when down.starts_on is not null then 'off_road' when drive.starts_on is not null then 'driving' else 'idle' end,
    coalesce(down.starts_on, drive.starts_on, greatest(
      c.start_day,
      (select max(a.ends_on) + 1 from public.driver_assignments a where a.car_id = c.id and a.ends_on < current_date),
      (select max(v.ends_on) + 1 from public.vehicle_downtime v where v.car_id = c.id and v.ends_on < current_date)
    ))
  from cars c
  left join totals t on t.car_id = c.id
  left join recent_rent r on r.car_id = c.id
  left join lateral (
    select v.starts_on from public.vehicle_downtime v
    where v.car_id = c.id and v.starts_on <= current_date and (v.ends_on is null or v.ends_on >= current_date)
    order by v.starts_on desc limit 1
  ) down on true
  left join lateral (
    select a.starts_on from public.driver_assignments a
    where a.car_id = c.id and a.starts_on <= current_date and (a.ends_on is null or a.ends_on >= current_date)
    order by a.starts_on desc limit 1
  ) drive on true
$$;
revoke all on function public.fleet_utilization(date, date, text) from public, anon;
grant execute on function public.fleet_utilization(date, date, text) to authenticated;
